// Scans the /nodes directory and writes lib/editor/registry.generated.ts.
//
// This exists so node files are genuinely drop-in: add a .ts file to
// /nodes and it appears in the editor with no other edit. A runtime glob
// isn't reliably available here (require.context is webpack-specific and
// import.meta.glob is a Vite thing), so this generates real static
// imports instead - which also keeps tree-shaking and type-checking
// working properly.
//
// Wired to npm `predev` and `prebuild`, so it runs automatically. If you
// add a node while the dev server is already running, restart it (or run
// `npm run gen:nodes` yourself).

import { readdirSync, writeFileSync, mkdirSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const nodesDir = join(root, 'nodes');
const outFile = join(root, 'lib', 'editor', 'registry.generated.ts');

if (!existsSync(nodesDir)) {
    mkdirSync(nodesDir, { recursive: true });
}

const files = readdirSync(nodesDir)
    .filter((f) => f.endsWith('.ts') && !f.endsWith('.d.ts') && !f.startsWith('_'))
    .sort();

const imports = files
    .map((f, i) => `import n${i} from '@/nodes/${f.replace(/\.ts$/, '')}';`)
    .join('\n');

const list = files.map((_, i) => `  n${i}`).join(',\n');

const body = `// AUTO-GENERATED by scripts/generate-node-registry.mjs
// Do not edit by hand - your changes will be overwritten.
// Add or remove files in /nodes instead; this regenerates on dev/build.

import type { NodeDefinition } from './types';

${imports}

export const generatedNodes: NodeDefinition[] = [
${list}
];
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, body);
console.log(`[nodes] registered ${files.length} node${files.length === 1 ? '' : 's'}`);